// Synthetic graph acceptance in Chromium; no external services or real learners.
const {chromium}=require('playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage();let speechRequests=0;
  await page.route('**/*',route=>{
   const url=new URL(route.request().url());
   if(url.origin!=='http://127.0.0.1:8765')return route.abort();
   if(url.pathname==='/')return route.fulfill({json:{status:'synthetic ready'}});
   if(url.pathname==='/api/classroom/session')return route.fulfill({json:{session_token:'synthetic-graph-session-token'}});
   if(url.pathname==='/api/classroom/visual')return route.fulfill({json:{title:'Points on y = 2x + 1',kind:'coordinate',items:[{label:'-1,-1',value:1},{label:'0,1',value:2},{label:'1,3',value:3}],caption:'Three points from this synthetic lesson.'}});
   if(url.pathname==='/api/classroom/chat')return route.fulfill({json:{reply:'Synthetic answer to the example question.'}});
   if(url.pathname==='/api/classroom/speech'){speechRequests++;return route.fulfill({contentType:'audio/L16',body:Buffer.alloc(240000)});}
   if(url.pathname==='/api/classroom/media')return route.fulfill({json:{kind:'replay',title:'Synthetic example',source:'Synthetic QA',steps:['Read the points.','Compare their coordinates.']}});
   if(url.pathname.startsWith('/api/'))return route.fulfill({status:503,json:{detail:'Not used'}});
   return route.continue();
  });
  fs.mkdirSync('responsive-qa',{recursive:true});
  for(const width of [375,390,768,1280]){
   await page.setViewportSize({width,height:900});
   await page.goto('http://127.0.0.1:8765/classroom/index.html');
   if(await page.getByRole('button',{name:'Essential only',exact:true}).isVisible())await page.getByRole('button',{name:'Essential only',exact:true}).click();
   await page.evaluate(()=>window.eval("learnerNickname.value='SyntheticGraphQA';learnerCode.value='TEST-GRAPH-QA';enterClassroomView();canvasEmpty.classList.add('hidden');canvasWork.classList.remove('hidden');startLessonDirector('Plot (-1,-1), (0,1) and (1,3).',0,['Plot the given coordinates.']);"));
   await page.evaluate(()=>window.eval("mediaRecorder={state:'recording'};setLearningStatus('Listening','listening')"));
   assert.equal(await page.locator('#teacherCue').getAttribute('data-state'),'listening');
   assert.equal(await page.locator('#teacherCue').evaluate(n=>getComputedStyle(n).color),'rgb(23, 53, 94)');
   await page.locator('#teacherPanel').screenshot({path:`responsive-qa/teacher-presence-${width}.png`});
   await page.evaluate(()=>window.eval("mediaRecorder=null;setLearningStatus('Preparing','thinking')"));
   assert.equal(await page.locator('#teacherCue').getAttribute('data-state'),'thinking');
   await page.locator('#showStepVisual').click();
   await page.locator('.coordinate-graph').waitFor({state:'visible'});
   assert.equal(await page.locator('#teacherCue').getAttribute('data-state'),'visual');
   const box=await page.locator('.coordinate-graph').boundingBox();assert.ok(box.width>0&&box.x>=0&&box.x+box.width<=width);
   await page.getByRole('button',{name:'Plot step by step',exact:true}).click();
   await page.getByRole('button',{name:'Plot next point',exact:true}).click();
   assert.match(await page.locator('#visualGraphic [role=status]').innerText(),/Point A.*1 left.*1 down/);
   assert.equal(await page.locator('.coordinate-graph g[visibility=visible]').count(),1);
   assert.equal(await page.locator('.graph-point-table td').count(),9);
   await page.locator('.coordinate-graph').screenshot({path:`responsive-qa/coordinate-graph-${width}.png`});
   await page.getByRole('button',{name:'Show all points',exact:true}).click();
   assert.equal(await page.locator('.coordinate-graph g[visibility=visible]').count(),3);
   await page.getByRole('button',{name:'Explain straight line',exact:true}).click();
   assert.equal(await page.locator('.graph-joined-line').count(),1);
   assert.match(await page.locator('#visualGraphic [role=status]').innerText(),/Gradient.*= 2\./);
   await page.getByRole('button',{name:'Plot step by step',exact:true}).click();
   assert.equal(await page.locator('.graph-joined-line').count(),0);
   await page.getByRole('button',{name:'Plot next point',exact:true}).click();
   await page.evaluate(()=>window.eval("executeHandsFreeIntent('Why is the first point left of the origin?')"));
   await page.waitForFunction(()=>document.getElementById('canvasAnswer').textContent==='Synthetic answer to the example question.');
   await page.evaluate(()=>window.eval("executeHandsFreeIntent('continue')"));
   await page.locator('.coordinate-graph').waitFor({state:'visible'});
   assert.equal(await page.locator('.coordinate-graph g[visibility=visible]').count(),1);
   assert.match(await page.locator('#visualGraphic [role=status]').innerText(),/Point A/);
   await page.getByRole('button',{name:'Plot next point',exact:true}).click();
   assert.equal(await page.locator('.coordinate-graph g[visibility=visible]').count(),2);
   await page.getByRole('button',{name:'Return to explanation',exact:true}).click();
   assert.equal(await page.locator('#canvasAnswer').innerText(),'Plot the given coordinates.');
   await page.evaluate(()=>window.eval('openLessonMedia()'));
   await page.locator('#mediaArea').waitFor({state:'visible'});
   assert.equal(await page.locator('#teacherPanel').evaluate(n=>n.classList.contains('minimized')),true);
   assert.equal(await page.locator('#toggleTeacher').getAttribute('aria-expanded'),'false');
   const replay=page.locator('#mediaReplay');
   assert.match(await replay.getByRole('status').innerText(),/step 1 of 2.*paused/);
   await replay.getByRole('button',{name:'Next example step',exact:true}).click();
   assert.match(await replay.getByRole('status').innerText(),/step 2 of 2.*complete/);
   const speechRequest=page.waitForRequest(r=>r.url().endsWith('/api/classroom/speech'));
   await replay.getByRole('button',{name:'Read example step',exact:true}).click();
   assert.equal((await speechRequest).postDataJSON().text,'Compare their coordinates.');
   assert.equal(await page.locator('#mediaArea').isVisible(),true);
   const pauseVoice=replay.getByRole('button',{name:'Pause example voice',exact:true});
   await page.waitForFunction(()=>!Array.from(document.querySelectorAll('#mediaReplay button')).find(b=>b.textContent==='Pause example voice').disabled);
   assert.equal(await page.locator('#teacherCue').getAttribute('data-state'),'speaking');
   const requestsBeforePause=speechRequests;
   await pauseVoice.click();
   await page.waitForFunction(()=>window.eval('teacherSpeechPaused && teacherAudioContext.state==="suspended"'));
   assert.equal(await page.locator('#teacherCue').getAttribute('data-state'),'paused');
   await replay.getByRole('button',{name:'Continue example voice',exact:true}).click();
   await page.waitForFunction(()=>window.eval('!teacherSpeechPaused && teacherAudioContext.state==="running"'));
   assert.equal(speechRequests,requestsBeforePause);
   assert.equal(await page.locator('#mediaArea').isVisible(),true);
   await replay.getByRole('button',{name:'Stop example voice',exact:true}).click();
   await replay.getByRole('button',{name:'Restart example',exact:true}).click();
   await replay.getByRole('button',{name:'Play example',exact:true}).click();
   await replay.getByRole('button',{name:'Pause example',exact:true}).click();
   assert.match(await replay.getByRole('status').innerText(),/paused/);
   await replay.getByRole('button',{name:'Next example step',exact:true}).click();
   await replay.getByRole('button',{name:'Ask about example step',exact:true}).click();
   await page.locator('#mediaArea').waitFor({state:'hidden'});
   await page.locator('#question').fill('Why compare these coordinates?');
   const chatRequest=page.waitForRequest(r=>r.url().endsWith('/api/classroom/chat'));
   await page.locator('#chatForm button[type=submit]').click();
   assert.match((await chatRequest).postDataJSON().message,/Compare their coordinates/);
   await page.waitForFunction(()=>document.getElementById('canvasAnswer').textContent==='Synthetic answer to the example question.');
   await page.locator('#returnToLesson').click();
   await page.locator('#mediaArea').waitFor({state:'visible'});
   assert.match(await replay.getByRole('status').innerText(),/step 2 of 2.*complete/);
   assert.equal(await replay.locator('p[aria-current=step]').innerText(),'2. Compare their coordinates.');
   const spokenQuestion=page.waitForRequest(r=>r.url().endsWith('/api/classroom/chat'));
   await page.evaluate(()=>window.eval("executeHandsFreeIntent('Why compare the coordinates?')"));
   assert.match((await spokenQuestion).postDataJSON().message,/Compare their coordinates/);
   await page.waitForFunction(()=>document.getElementById('canvasAnswer').textContent==='Synthetic answer to the example question.');
   const continuedSpeech=page.waitForRequest(r=>r.url().endsWith('/api/classroom/speech'));
   await page.evaluate(()=>window.eval("executeHandsFreeIntent('continue')"));
   assert.equal((await continuedSpeech).postDataJSON().text,'Compare their coordinates.');
   await page.locator('#mediaArea').waitFor({state:'visible'});
   assert.match(await replay.getByRole('status').innerText(),/step 2 of 2/);
   await page.evaluate(()=>window.eval("executeHandsFreeIntent('previous step')"));
   assert.match(await replay.getByRole('status').innerText(),/step 1 of 2/);
   await page.evaluate(()=>window.eval("executeHandsFreeIntent('next step')"));
   assert.match(await replay.getByRole('status').innerText(),/step 2 of 2/);
   const repeatedSpeech=page.waitForRequest(r=>r.url().endsWith('/api/classroom/speech'));
   await page.evaluate(()=>window.eval("executeHandsFreeIntent('repeat')"));
   assert.equal((await repeatedSpeech).postDataJSON().text,'Compare their coordinates.');
   await replay.getByRole('button',{name:'Stop example voice',exact:true}).click();
   const speechBeforeReload=speechRequests;
   await page.reload();
   await page.locator('#learnerConsent').check();
   await page.locator('#resumeLearning').click();
   await page.locator('#mediaArea').waitFor({state:'visible'});
   assert.match(await replay.getByRole('status').innerText(),/step 2 of 2.*complete/);
   assert.equal(await replay.locator('p[aria-current=step]').innerText(),'2. Compare their coordinates.');
   assert.equal(speechRequests,speechBeforeReload);
   assert.equal(await replay.getByRole('button',{name:'Pause example voice',exact:true}).isEnabled(),false);
   await page.locator('#closeMedia').click();
   await page.locator('#mediaArea').waitFor({state:'hidden'});
   assert.equal(await page.locator('#teacherPanel').evaluate(n=>n.classList.contains('minimized')),false);
   assert.equal(await page.locator('#toggleTeacher').getAttribute('aria-expanded'),'true');
   assert.equal(await page.locator('#canvasAnswer').innerText(),'Plot the given coordinates.');
  }
  console.log('Guided coordinate plot, table and lesson return at 375/390/768/1280px: PASS');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1});
